#!/usr/bin/env node
// Builds js/cms.js from the calendar cards in content/calendar/*.json (edited in Pages CMS, see .pages.yml).
// Run: node scripts/build-content.mjs   (the "Build content" GitHub Action runs it on every save)

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, basename } from 'node:path';

const DIR = 'content/calendar';
const OUT = 'js/cms.js';

/* ── Text ───────────────────────────────────────────── */
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
// plain text with *one word* in italics, the way the cards set their accent
const rich = (s) => (s ? esc(s.trim()).replace(/\*([^*\n]+)\*/g, '<em>$1</em>') : undefined);
const plain = (s) => (s ? s.trim().replace(/\*([^*\n]+)\*/g, '$1') : '');
// only plain web links and image paths inside assets/
const safeHref = (u) => (u && /^https?:\/\/[^\s"'<>]+$/i.test(u.trim()) ? u.trim() : undefined);
const safeImg = (p) => typeof p === 'string' && /^assets\/[\w\-./]+\.(jpe?g|png|webp|gif|avif)$/i.test(p) && !p.includes('..');
// write-ups come from the rich-text editor; drop anything that could run
const cleanHTML = (h) => (h && h.trim()
  ? h.replace(/<(script|style|iframe|object|embed)[\s\S]*?<\/\1>/gi, '').replace(/\son\w+="[^"]*"/gi, '').replace(/javascript:/gi, '')
  : undefined);
const idOf = (file) => basename(file, '.json');

/* ── Cards → events ─────────────────────────────────── */
function toEvent(r, byPath) {
  if (!r.date || !r.card) { console.warn(`  skipped "${r.name || r.file}": needs a Date and a Card`); return null; }
  const title = rich(r.name);
  const summary = rich(r.summary);
  const photos = (r.photos || []).filter(safeImg);
  const pics = photos.length ? photos : undefined;
  const parent = r.part_of && byPath.get(r.part_of);
  const client = (r.client || '').trim();
  const live = safeHref(r.live);
  const base = {
    id: idOf(r.file),
    date: r.date,
    highlight: r.highlight || undefined,
    tbc: r.placeholder_date || undefined,
    color: r.color ? r.color.toLowerCase() : undefined,
  };
  switch (r.card) {
    case 'Quote': return { ...base, type: 'quote', title };
    case 'Note': return { ...base, type: 'note', title, detail: summary, photos: pics };
    case 'Logos': return { ...base, type: 'logos', title };
    case 'Snippets': return { ...base, type: 'snippets', title };
    case 'Person': {
      const [name, role = ''] = client.split(/\s+·\s+/);
      const links = live ? [{ label: live.replace(/^https?:\/\/(www\.)?/, ''), href: live }] : [];
      return { ...base, type: 'person', title, photos: pics, who: { name, role, short: name.split(' ')[0], mono: (name[0] || '?').toUpperCase(), bio: summary, links } };
    }
    case 'Testimonial':
      return { ...base, type: 'testimonial', who: { name: plain(r.name), role: client, img: photos[0], quote: plain(r.summary) } };
    case 'Milestone':
      return r.kind === 'Work'
        ? { ...base, type: 'milestone', title, metric: r.metric || undefined, sub: plain(r.summary) || undefined, case: r.case_study || undefined, section: r.case_section || undefined, client: client || parent?.client || undefined }
        : { ...base, type: 'milestone', title, metric: r.metric || undefined, detail: summary };
    case 'Project':
      if (r.case_study) return { ...base, type: 'case', case: r.case_study, end: r.end || undefined };
      return { ...base, type: 'project', title, client, summary, services: r.services || [], photos: pics, live, end: r.end || undefined, body: cleanHTML(r.body) };
    case 'Moment':
      if (r.case_study) return { ...base, type: 'step', case: r.case_study, section: r.case_section || undefined, title, img: photos[0] };
      return { ...base, type: 'moment', title, client: client || parent?.client, summary, services: r.services || [], photos: pics, live, parent: parent ? idOf(parent.file) : undefined, body: cleanHTML(r.body) };
  }
  console.warn(`  skipped "${r.name}": unknown Card "${r.card}"`);
  return null;
}

/* ── Run ────────────────────────────────────────────── */
const rows = readdirSync(DIR).filter((f) => f.endsWith('.json')).sort().map((f) => {
  const file = join(DIR, f);
  return { ...JSON.parse(readFileSync(file, 'utf8')), file };
});
const byPath = new Map(rows.map((r) => [r.file, r]));
const events = rows
  .filter((r) => r.publish)
  // by date; cards on the same day keep their "order within the day", then their name
  .sort((a, b) => (a.date || '').localeCompare(b.date || '') || (a.order ?? 999) - (b.order ?? 999) || (a.name || '').localeCompare(b.name || ''))
  .map((r) => toEvent(r, byPath))
  .filter(Boolean);

const out = `// Generated by scripts/build-content.mjs from content/calendar/ (edit the cards in Pages CMS, not here).
// The next save in Pages CMS rebuilds this file.
window.CMS = ${JSON.stringify({ events }, null, 1)};
`;
writeFileSync(OUT, out);
console.log(`Wrote ${OUT}: ${events.length} cards (${rows.length - events.length} unpublished or skipped).`);
